/// 横書き用の文字を縦書き用の字形に変換するユーティリティ
class GlyphMapper {
  GlyphMapper._();

  /// 文字を縦書き用の字形に変換する
  ///
  /// マッピングが存在しない場合はそのまま返す
  static String map(String char) {
    return _mapping[char] ?? char;
  }

  static const _mapping = <String, String>{
    // スペース
    ' ': '　',

    // 矢印
    '↑': '→',
    '↓': '←',
    '←': '↑',
    '→': '↓',

    // 句読点
    '。': '︒',
    '、': '︑',
    ',': '︐',
    '､': '︑',
    '.': '﹒', // U+002E → U+FE52 縦書き小点
    '!': '︕', // U+0021 → U+FE15 縦書き感嘆符
    '?': '︖', // U+003F → U+FE16 縦書き疑問符
    // 長音・ダッシュ
    'ー': '丨',
    '─': '丨',
    '-': '丨',
    'ｰ': '丨',
    '_': '丨',
    '−': '丨',
    '－': '丨',
    '—': '丨',
    '―': '丨', // U+2015 HORIZONTAL BAR
    '–': '丨', // U+2013 EN DASH
    '‐': '丨', // U+2010 HYPHEN
    '〜': '丨',
    '～': '丨',
    // ダッシュの代わりに使われる記号（フォークで追加）。
    // 「フル─スロットル」のように、罫線などを長音・ダッシュとして書く文章があるため
    '‒': '丨', // U+2012 FIGURE DASH
    '⁃': '丨', // U+2043 HYPHEN BULLET
    '⎯': '丨', // U+23AF HORIZONTAL LINE EXTENSION
    '⸺': '丨', // U+2E3A TWO-EM DASH
    '⸻': '丨', // U+2E3B THREE-EM DASH
    '﹘': '丨', // U+FE58 SMALL EM DASH
    '﹣': '丨', // U+FE63 SMALL HYPHEN-MINUS
    // 横の罫線は、対応する縦の罫線にする（太さ・破線の種類を保つ）
    '━': '┃', // U+2501 → U+2503
    '┄': '┆', // U+2504 → U+2506
    '┅': '┇', // U+2505 → U+2507
    '┈': '┊', // U+2508 → U+250A
    '┉': '┋', // U+2509 → U+250B
    '╌': '╎', // U+254C → U+254E
    '╍': '╏', // U+254D → U+254F
    '═': '║', // U+2550 → U+2551
    '╴': '╵', // U+2574 → U+2575
    '╶': '╷', // U+2576 → U+2577
    '╸': '╹', // U+2578 → U+2579
    '╺': '╻', // U+257A → U+257B
    '╼': '╽', // U+257C → U+257D
    '╾': '╿', // U+257E → U+257F

    // その他記号
    '／': '＼',
    '…': '︙',
    '‥': '︰',
    '︙': '…',
    '：': '︓',
    ':': '︓',
    '；': '︔',
    ';': '︔',
    '・': '｜', // U+30FB カタカナ中点
    '･': '｜', // U+FF65 半角カタカナ中点
    '＝': '॥',
    '=': '॥',

    // 丸括弧
    '（': '︵',
    '(': '︵',
    '）': '︶',
    ')': '︶',

    // 角括弧
    '［': '﹇',
    '[': '﹇',
    '］': '﹈',
    ']': '﹈',

    // 波括弧
    '｛': '︷',
    '{': '︷',
    '｝': '︸',
    '}': '︸',

    // 山括弧
    '＜': '︿',
    '<': '︿',
    '＞': '﹀',
    '>': '﹀',

    // 鉤括弧
    '「': '﹁',
    '」': '﹂',
    '『': '﹃',
    '』': '﹄',
    '｢': '﹁',
    '｣': '﹂',

    // 隅付き括弧
    '【': '︻',
    '】': '︼',
    '〖': '︗',
    '〗': '︘',

    // 二重山括弧
    '《': '︽', // U+300A → U+FE3D 縦書き二重山括弧左
    '》': '︾', // U+300B → U+FE3E 縦書き二重山括弧右
  };
}
